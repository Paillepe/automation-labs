// Accès à PostgreSQL. La base est facultative : sans elle, l'application démarre et /ready répond 503.

import pg from 'pg';

const SCHEMA = `
create table if not exists reservation (
  id bigint generated by default as identity primary key,
  numero_carte varchar(9) not null,
  titre varchar(80) not null,
  site_id integer not null,
  creee_le timestamptz not null default now(),
  retrait_avant date not null
)`;

// Traduit une erreur du pilote en une raison lisible, pour /ready et pour les logs.
export function describeDbError(err) {
  switch (err?.code) {
    case '28P01':
      return 'authentification refusée par la base (mot de passe ou utilisateur)';
    case '3D000':
      return 'la base demandée n\'existe pas';
    case 'ENOTFOUND':
    case 'EAI_AGAIN':
      return `nom d'hôte de la base introuvable (${err.hostname ?? 'DB_HOST'})`;
    case 'ECONNREFUSED':
      return 'connexion refusée par l\'hôte de la base';
    default:
      if (/timeout/i.test(err?.message ?? '')) return 'la base ne répond pas (délai dépassé)';
      return `base injoignable : ${err?.code ?? err?.message ?? 'erreur inconnue'}`;
  }
}

export function createDb(config) {
  if (!config) {
    return {
      configured: false,
      async check() {
        return { ok: false, reason: 'aucune base configurée (DB_HOST absent)' };
      },
      async query() {
        throw Object.assign(new Error('aucune base configurée'), { code: 'NO_DB' });
      },
      async close() {},
    };
  }

  const pool = new pg.Pool({
    ...config,
    max: 5,
    connectionTimeoutMillis: 2000,
    idleTimeoutMillis: 10000,
    query_timeout: 3000,
    application_name: 'reservations',
  });
  // Une connexion inactive qui tombe (base redémarrée) ne doit pas arrêter le processus.
  pool.on('error', () => {});

  let schemaReady = false;

  async function query(text, params) {
    if (!schemaReady) {
      await pool.query(SCHEMA);
      schemaReady = true;
    }
    return pool.query(text, params);
  }

  return {
    configured: true,
    async check() {
      try {
        await query('select 1');
        return { ok: true };
      } catch (err) {
        schemaReady = false;
        return { ok: false, reason: describeDbError(err) };
      }
    },
    query,
    async close() {
      await pool.end().catch(() => {});
    },
  };
}
